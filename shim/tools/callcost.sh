#!/bin/bash
# What one call of halo3's hottest Win32 imports costs under Rosetta, called the way the guest calls them (backlog 11/41).
# tools/callcost.c runs Win64 caller loops from writable+executable memory (translated like guest code), each doing
# `call [slot]` into: the loader's REAL implementations (cut from src/peload.c / src/wininput.c by marker below, so the
# numbers follow the source), the fast paths in src/fastcall.c (PELOAD_FASTCALL), and building blocks that separate the
# costs (empty leaf, leaf in loader text vs generated code, ms_abi -> SysV transition, malloc/free, the guest CRT's own
# memset/memcpy/towlower when the Microsoft CRT is found). Then the fast paths are checked against the originals (HeapSize per
# request size, zeroing, realloc, key state, thread id) and the fast heap is stress-tested on 8 threads with the A/B flipping
# under load (exit status 1 on any failure).
#     bash shim/tools/callcost.sh [quick]        (needs no game; a busy machine widens the numbers: CPU time per call)
# RECLAIMER_CRT_DIR=<dir with ucrtbase.dll + vcruntime140.dll> picks the CRT (default: as the loader looks for it).
set -e
cd "$(dirname "$0")/.."
T=$(mktemp -d "${TMPDIR:-/tmp}/callcost.XXXXXX"); trap 'rm -rf "$T"' EXIT
# a block by marker: from the first line starting with START up to (not including) the first later line starting with END
cut_block(){ awk -v s="$2" -v e="$3" 'index($0,s)==1{on=1} on && index($0,e)==1 && !(index($0,s)==1){exit} on{print}' "$1"; }
{
  echo '// generated by tools/callcost.sh from src/peload.c and src/wininput.c -- the loader'"'"'s real implementations'
  cut_block src/peload.c 'static __thread uint32_t t_tid;' 'static uint32_t MSABI i_GetCurrentProcessId'
  cut_block src/peload.c '// Win32 heap backed by malloc' 'static void*  MSABI i_HeapCreate'
  cut_block src/peload.c 'static uint32_t g_tlsnext=1;' 'static int    MSABI i_TlsFree'
  cut_block src/wininput.c 'static volatile uint8_t g_keydown[256];' 'static volatile uint8_t g_keytoggle'
  cut_block src/wininput.c 'static __thread int t_damp=-1' 'static int16_t MSABI wi_GetKeyState'
  cut_block src/peload.c 'static void* crt_fast_stub' '// unified resolver'
} > "$T/callcost_orig.inc"
for f in 'i_GetCurrentThreadId' 'i_HeapAlloc' 'i_TlsGetValue' 'wi_GetAsyncKeyState' 'crt_fast_stub'; do
  grep -q "$f" "$T/callcost_orig.inc" || { echo "callcost: could not cut $f out of the loader source"; exit 1; }
done
CRT="${RECLAIMER_CRT_DIR:-}"
for c in "$CRT" "build/crt" "crt" "$HOME/Desktop/HaloReclaimerMac/shim/crt" "$HOME/Library/Application Support/ReclaimerMac/ms-crt"; do
  [ -n "$c" ] && [ -f "$c/vcruntime140.dll" ] && { CRT="$c"; break; }
done
clang -arch x86_64 -O1 -Wno-deprecated-declarations -I"$T" -Isrc -o "$T/callcost" tools/callcost.c
arch -x86_64 "$T/callcost" "$CRT" "$@"
