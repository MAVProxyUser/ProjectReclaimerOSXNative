#!/usr/bin/env python3
# com_slots.py -- COM vtable layouts from Wine's IDL files -> shim/src/d2d_slots.h (2026-10-21).
# Wine declares every interface's methods in vtable order (MSVC's reversed overload order included), so the slot of a
# method = its index after the base interface's slots. The header gives d2d.c / dwrite / WIC their IIDs and the method
# name of every slot (the logging fallback for a slot the shim does not implement prints it).
#   python3 shim/tools/com_slots.py <wine>/include/{d2d1,d2d1_1,dcommon,dwrite,dwrite_1,dwrite_2,dwrite_3,objidlbase,wincodec}.idl \
#       > shim/src/d2d_slots.h
# (the IDL files: https://gitlab.winehq.org/wine/wine/-/tree/master/include)
import re, sys

WANT = """IUnknown ID2D1Resource ID2D1Image ID2D1Factory ID2D1Factory1 ID2D1Device ID2D1RenderTarget ID2D1DeviceContext
ID2D1Bitmap ID2D1Bitmap1 ID2D1Brush ID2D1SolidColorBrush ID2D1LinearGradientBrush ID2D1RadialGradientBrush ID2D1BitmapBrush
ID2D1BitmapBrush1 ID2D1GradientStopCollection ID2D1GradientStopCollection1 ID2D1Geometry ID2D1RectangleGeometry
ID2D1RoundedRectangleGeometry ID2D1EllipseGeometry ID2D1GeometryGroup ID2D1TransformedGeometry ID2D1PathGeometry
ID2D1PathGeometry1 ID2D1SimplifiedGeometrySink ID2D1GeometrySink ID2D1StrokeStyle ID2D1StrokeStyle1 ID2D1Layer
ID2D1DrawingStateBlock ID2D1DrawingStateBlock1
IDWriteFactory IDWriteFactory1 IDWriteFactory2 IDWriteFactory3 IDWriteFactory4 IDWriteFactory5 IDWriteFontCollection
IDWriteFontCollection1 IDWriteFontFileLoader IDWriteInMemoryFontFileLoader IDWriteFontFile IDWriteFontSetBuilder
IDWriteFontSetBuilder1 IDWriteFontSet IDWriteTextFormat IDWriteTextLayout IDWriteRenderingParams IDWriteTypography
IDWriteInlineObject IDWriteFontFamily IDWriteFontList IDWriteFont IDWriteLocalizedStrings
ISequentialStream IStream IWICImagingFactory IWICBitmapSource IWICStream IWICBitmapDecoder IWICBitmapFrameDecode
IWICFormatConverter IWICBitmap IWICBitmapLock IWICBitmapScaler""".split()

src = ''.join(open(f, encoding='utf-8', errors='replace').read() + '\n' for f in sys.argv[1:])
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S); src = re.sub(r'//[^\n]*', '', src); src = re.sub(r'(?m)^\s*#.*$', '', src)
ifaces = {}
for m in re.finditer(r'(\[[^\[\]]*\])?\s*interface\s+(\w+)\s*:\s*(\w+)\s*\{', src):
    attrs, name, base = m.group(1) or '', m.group(2), m.group(3)
    u = re.search(r'uuid\(\s*([0-9a-fA-F-]{36})\s*\)', attrs)
    i = m.end(); depth = 1; j = i
    while depth and j < len(src):
        depth += {'{': 1, '}': -1}.get(src[j], 0); j += 1
    meths = []
    for stmt in src[i:j-1].split(';'):
        if 'call_as' in stmt: continue          # [call_as(X)] RemoteX: the RPC form of X, not a vtable slot
        st = re.sub(r'\[[^\]]*\]', '', stmt).strip()
        mm = re.search(r'(\w+)\s*\(', st)
        if mm and not st.startswith('typedef') and mm.group(1) != 'cpp_quote': meths.append(mm.group(1))
    ifaces[name] = (base, meths, u.group(1).lower() if u else None)
ifaces['IUnknown'] = (None, ['QueryInterface', 'AddRef', 'Release'], '00000000-0000-0000-c000-000000000046')

def slots(n):
    b, m, _ = ifaces[n]
    return (slots(b) if b else []) + m

print('// d2d_slots.h -- generated by shim/tools/com_slots.py from Wine\'s IDL; do not edit. Per interface: its IID and the method')
print('// name of every vtable slot (in vtable order).')
for n in WANT:
    if n not in ifaces: sys.exit('missing interface ' + n)
    s = slots(n); u = ifaces[n][2]
    a, b, c, d = u[0:8], u[9:13], u[14:18], u[19:23] + u[24:]
    by = ','.join('0x' + d[k:k+2] for k in range(0, 16, 2))
    if n != 'IUnknown': print(f'static const GUID_ IID_{n}={{0x{a},0x{b},0x{c},{{{by}}}}};')   # (IID_IUnknown: peload.c's)
    print(f'enum {{ NSLOT_{n}={len(s)} }};')
    print(f'static const char*const SLOTS_{n}[{len(s)}]={{' + ','.join(f'"{x}"' for x in s) + '};')
